import assert from 'node:assert/strict';
import {createScoreHarness} from './helpers/score-harness.mjs';
import {logoFixture} from './helpers/logo-fixture.mjs';
const {context:c,props,sheets}=createScoreHarness();c.setupScoreMvp_();
props.set('SCORE_ADMIN_KEY','SYNTHETIC-BRANDING-ADMIN-ONLY');c.configureScoreAdmin_();
const call=d=>c.scoreRoute_(d),initial=call({action:'score.branding'});
assert.equal(initial.name,'RCM Examinations & Records');assert.equal(initial.logoData,'');assert.equal(initial.defaultTheme,'aurora');
assert.throws(()=>call({action:'score.admin.branding.save',revision:initial.revision,logoData:logoFixture(),defaultTheme:'ocean'}),/Administrator session/);
const token=call({action:'score.admin.login',key:'SYNTHETIC-BRANDING-ADMIN-ONLY'}).token,save=d=>call({action:'score.admin.branding.save',token,revision:initial.revision,logoData:logoFixture(),defaultTheme:'ocean',...d});
assert.throws(()=>save({logoData:'data:image/svg+xml;base64,AAAA'}),/supported image/);
assert.throws(()=>save({logoData:'data:image/png;base64,AAAA'}),/Invalid PNG/);
assert.throws(()=>save({defaultTheme:'unknown'}),/Choose Aurora/);
assert.equal(sheets.get('ScorePortalSettings').data.length,1);
const saved=save({});assert.equal(saved.logoData,logoFixture());assert.equal(call({action:'score.branding'}).defaultTheme,'ocean');
assert.ok(!JSON.stringify(call({action:'score.branding'})).includes('SYNTHETIC-BRANDING-ADMIN'));
assert.throws(()=>save({}),/Branding changed/);
const restored=save({revision:saved.revision,logoData:'',defaultTheme:'classic'});assert.equal(restored.logoData,'');assert.equal(restored.defaultTheme,'classic');
assert.equal(sheets.get('ScorePortalSettings').data.length,3,'Keep append-only branding audit history');
console.log('PASS: shared branding read, admin-only publication, PNG validation, theme allowlist, stale-save protection and original-logo recovery.');
