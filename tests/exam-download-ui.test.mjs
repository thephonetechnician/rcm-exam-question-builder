import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync(new URL('../exam-builder.html',import.meta.url),'utf8');
const release=html.match(/data-exam-release="([^"]+)"/)[1];
const ui=fs.readFileSync(new URL('../js/ui.js',import.meta.url),'utf8');
const generator=fs.readFileSync(new URL('../js/document-generator.js',import.meta.url),'utf8');
for(const file of ['config','google-drive','exam-builder','document-generator','validation','ui','exam-preview','app'])assert.ok(html.includes(`js/${file}.js?v=${release}`),file+' must load from the matching release');
assert.ok(html.includes('assets/vendor/jszip.min.js?v='+release));
const checkbox={checked:true},document={documentElement:{dataset:{examRelease:release}},getElementById:()=>checkbox};
const ctx=vm.createContext({document});vm.runInContext(generator,ctx);vm.runInContext(ui,ctx);
const old={semester:'First',questions:[],courseTitle:'Preserved source'};
assert.equal(ctx.examDownloadData(old).includeSignatureLines,true);
checkbox.checked=false;assert.equal(ctx.examDownloadData(old).includeSignatureLines,false);
assert.equal(ctx.examDownloadData(old,true).includeSignatureLines,true,'Saved downloads honour the option captured when clicked');
assert.equal(old.includeSignatureLines,undefined,'Do not modify an archived paper');
document.documentElement.dataset.examRelease='outdated';assert.throws(()=>ctx.examDownloadData(old),/formatter needs to refresh/);
const missing=vm.createContext({document});vm.runInContext(ui,missing);assert.throws(()=>missing.examDownloadData(old),/formatter needs to refresh/);
console.log('PASS: versioned builder assets, formatter mismatch guard, shared new/saved download options and immutable saved records.');
